//! Проверка и установка обновлений (план 5, задача 3).
//!
//! Источник — только `denislibs/proxy-pilot`: репозиторий, которым владеет
//! партнёр, опубликовавший эту работу (`docs/process/win-delivery/progress.md`,
//! «БЛОКЕР СНЯТ»). Автообновление, тянущее исполняемый файл из чужого
//! репозитория, — канал доставки чужого кода прямо в процесс, который правит
//! ключи прокси в реестре и держит слушающий сокет; это условие не
//! конфигурируется и не выведено в UI как настройка.
//!
//! Модули:
//! - [`version`] — чистое сравнение версий, без сети и без диска.
//! - [`verify`] — проверка подписи Authenticode скачанного файла. Отказ на
//!   отсутствующей и на неверной подписи, без исключений и без выключателя:
//!   это единственное, что отличает обновление от доставки чужого кода.
//! - [`source`] — сетевой источник (GitHub Releases API + скачивание файла)
//!   за трейтом: тесты подставляют фиктивную реализацию, реальная
//!   (`GithubSource`) не участвует ни в одном тесте — сеть в тестах запрещена
//!   прямым ограничением задачи.
//! - [`check`] — фоновая проверка: не блокирует старт (вызывающий обязан
//!   звать её через `tokio::spawn`, а не `block_on`), при выключенном
//!   тумблере проверки не трогает сеть вовсе, при найденном обновлении
//!   скачивает и проверяет подпись — установка происходит только если обе
//!   проверки (подпись присутствует И верна) прошли.
//! - [`install`] — применение уже скачанного и проверенного обновления при
//!   СЛЕДУЮЩЕМ запуске, не под работающим процессом.
pub mod check;
pub mod install;
mod json;
pub mod source;
pub mod verify;
pub mod version;
