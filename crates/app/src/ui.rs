//! Обращения к пользователю средствами Windows.
//!
//! Отдельным модулем, а не строкой в `main`. В релизной сборке у процесса
//! нет консоли (`windows_subsystem = "windows"`), поэтому `eprintln!` не
//! читает никто: отказ на старте выглядит как «двойной клик — и ничего не
//! произошло», без окна, без иконки, без сообщения. `MessageBoxW` — то
//! единственное, чем можно ответить человеку до появления собственного окна;
//! окно настроек этапа 3 попросит ровно этот же примитив.

use windows::core::{w, HSTRING, PCWSTR};
use windows::Win32::Foundation::HWND;
use windows::Win32::UI::Shell::ShellExecuteW;
use windows::Win32::UI::WindowsAndMessaging::{
    MessageBoxW, MB_ICONERROR, MB_OK, MB_SETFOREGROUND, SW_SHOWNORMAL,
};

/// Модальное окно с ошибкой. Блокирует вызывающий поток, пока человек его не
/// закроет, — и это здесь единственно верное поведение: сообщение об отказе
/// старта обязано быть прочитано раньше, чем процесс уйдёт.
///
/// `MB_SETFOREGROUND` не косметика: у процесса без окон нет и активности, и
/// без этого флага окно может открыться под уже работающими — то есть снова
/// остаться незамеченным.
pub fn error_box(title: &str, text: &str) {
    let title = HSTRING::from(title);
    let text = HSTRING::from(text);
    // SAFETY: окна-владельца нет намеренно — отказ может случиться до того,
    // как трей создаст своё окно. Обе строки живы до возврата вызова, а
    // возврата не будет, пока окно не закрыто. Результат нам не нужен:
    // кнопка одна, и любой исход означает «прочитано».
    unsafe {
        MessageBoxW(
            HWND::default(),
            &text,
            &title,
            MB_OK | MB_ICONERROR | MB_SETFOREGROUND,
        );
    }
}

/// Открывает адрес тем, что назначено у пользователя для `http`.
///
/// Окно настроек — это страница, которую приложение отдаёт само (`websrv`),
/// и показать её больше нечем: собственного окна у процесса нет, а второй
/// GUI-фреймворк ради него не заводится сознательно (см. модульный
/// комментарий `websrv`).
///
/// Отказ возвращается, а не глотается: человек нажал пункт меню и обязан
/// либо увидеть страницу, либо узнать, почему её нет.
pub fn open_in_browser(url: &str) -> Result<(), String> {
    let url = HSTRING::from(url);
    // SAFETY: обе строки живы до конца вызова, окна-владельца нет намеренно
    // — у процесса его и не бывает. `ShellExecuteW` возвращает не дескриптор,
    // а код: успехом считается всё, что больше 32, — это наследие 16-битной
    // Windows, прямо оговорённое в её документации.
    let code = unsafe {
        ShellExecuteW(
            HWND::default(),
            w!("open"),
            &url,
            PCWSTR::null(),
            PCWSTR::null(),
            SW_SHOWNORMAL,
        )
    };
    let code = code.0 as usize;
    if code > 32 {
        Ok(())
    } else {
        Err(format!("ShellExecuteW вернула {code}"))
    }
}

/// Запускает `exe` заново с параметрами `args` и запросом повышения прав —
/// `ShellExecuteW` c `lpOperation = "runas"`, тем самым Windows сама
/// показывает диалог UAC.
///
/// Единственный вызывающий во всём продукте (задача 7) — кнопка
/// «Установить службу статического IP» на странице настроек
/// (`settings_page::Tunnel::install_service`): `install-service` остаётся
/// единственным запросом прав во всём приложении (`CLAUDE.md`, «Права
/// администратора»), эта функция лишь даёт до него дотянуться из уже
/// работающего (не повышенного) процесса, а не только из ручного запуска в
/// консоли администратором.
///
/// `Ok` значит только «запрос дошёл до `ShellExecuteW`, и она вернула код
/// успеха» — не «UAC принят» и не «служба установлена»: пользователь может
/// отклонить диалог, и узнать об этом отсюда нельзя (тот же контракт, что у
/// `open_in_browser` выше и у `openvpn::connect` в `winnet`).
pub fn request_elevation(exe: &std::path::Path, args: &str) -> Result<(), String> {
    let exe = HSTRING::from(exe.as_os_str());
    let args = HSTRING::from(args);
    // SAFETY: обе строки живы до конца вызова; окна-владельца нет намеренно
    // — тот же случай, что и в `open_in_browser`. `lpOperation = "runas"` —
    // то, что просит у Windows диалог согласия на повышение прав.
    let code = unsafe {
        ShellExecuteW(
            HWND::default(),
            w!("runas"),
            &exe,
            &args,
            PCWSTR::null(),
            SW_SHOWNORMAL,
        )
    };
    let code = code.0 as usize;
    if code > 32 {
        Ok(())
    } else {
        Err(format!("ShellExecuteW (runas) вернула {code}"))
    }
}
