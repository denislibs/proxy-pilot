//! Служба Windows `ProxyPilotNetProfile` — статический IP в офисе.
//!
//! Отдельный крейт, а не код в основном приложении, ровно по одной причине:
//! смена IPv4-адреса требует прав администратора, а ядро продукта обязано
//! оставаться без единого запроса UAC (`CLAUDE.md`, «Права администратора»).
//! Единственный запрос прав во всём продукте — установка этой службы, один
//! раз, и только тем, кому статика вообще нужна.
//!
//! Служба читает **свою собственную** копию профиля,
//! `%ProgramData%\ProxyPilot\profile.toml` (`profile::path`), а не
//! пользовательский `%APPDATA%\ProxyPilot\config.toml`. Служба работает от
//! LocalSystem; читать файл из профиля пользователя, который сам
//! пользователь и правит, от системной учётной записи — значит открыть путь
//! к подмене: кто угодно с доступом на запись к пользовательскому файлу
//! диктовал бы системной службе, какие сетевые настройки применять.
//!
//! Решение о том, ЧТО применить (статика/DHCP/не трогать), не принимается
//! здесь: этим целиком владеет `proxypilot_core::netprofile::decide_profile`
//! (задача 5), полностью покрытая табличными тестами там. Этот крейт только
//! превращает готовое решение в команды `netsh` (`netsh_cmd`) и добавляет
//! страховку (`safety`) — проверку достижимости шлюза с откатом в DHCP.
//!
//! Модули:
//! - [`profile`] — разбор `profile.toml` службы;
//! - [`netsh_cmd`] — построение команд `netsh interface ipv4 ...`, без
//!   исполнения;
//! - [`safety`] — решение об откате в DHCP при недостижимом шлюзе;
//! - [`adapter`] — сопоставление GUID офисной сети (NLM) с псевдонимом
//!   адаптера, который ожидает `netsh ... name=`, и чтение текущего
//!   IPv4-состояния адаптера;
//! - [`state`] — собственная память службы о последнем применённом ею
//!   значении (`AppliedState`) — единственный способ узнать «это поставили
//!   мы», раз Windows такого признака не хранит;
//! - [`install`] — регистрация/снятие службы через Service Control Manager
//!   (`CreateServiceW`/`DeleteService`) — вызывается только командами
//!   `install-service`/`uninstall-service` приложения, человеком, с UAC;
//!   `uninstall` дополнительно возвращает адаптер на DHCP, если служба
//!   владела статикой (ревью round 2, Important №8) — после `DeleteService`
//!   вернуть её больше некому;
//! - [`exec`] — единственное место в крейте, которое реально запускает
//!   `netsh`, с таймаутом и проверкой кода возврата; делят `main.rs` и
//!   `install::uninstall`.
//!
//! `main.rs` (двоичная цель `proxypilot-netsvc`, не часть библиотеки) —
//! вход SCM: `StartServiceCtrlDispatcherW`, обработчик управления, главный
//! цикл. Не тестируется автоматически в принципе — либо запущен
//! диспетчером служб Windows, либо не запускается вовсе (докблок
//! `main.rs`).

pub mod adapter;
pub mod exec;
pub mod install;
pub mod netsh_cmd;
pub mod profile;
pub mod safety;
pub mod state;

/// Имя службы в Service Control Manager — то, что видно в `services.msc` и
/// чем `sc.exe`/`Get-Service` её адресуют.
pub const SERVICE_NAME: &str = "ProxyPilotNetProfile";

/// Отображаемое имя — то, что человек видит в списке служб.
pub const SERVICE_DISPLAY_NAME: &str = "ProxyPilot Net Profile";
